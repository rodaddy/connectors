/**
 * Generate `src/webhooks/event-names.ts` from the committed
 * `catalog/webhook-catalog.json`: one string-literal union of every event `type`.
 * `npm run catalog:generate` runs it after the webhook catalog.
 *
 * @module
 */
import { readFile, writeFile } from "node:fs/promises";
import { basename, join, resolve } from "node:path";

import { format } from "prettier";

import type { WebhookCatalog } from "../src/catalog/types.ts";
import { say } from "./out.ts";
import { catalogRoot } from "./upstream.ts";

const target = resolve(import.meta.dirname, "../src/webhooks/event-names.ts");

const catalog = JSON.parse(
  await readFile(join(catalogRoot, "webhook-catalog.json"), "utf8"),
) as WebhookCatalog;
// The catalog's `event` is the doc example's `type`, and some pages copy
// another page's example (AppointmentUpdate/Delete say AppointmentCreate), so
// names come from the doc file names. A page whose file name is not the `type`
// GHL sends is renamed here: the app lifecycle types and the unread page.
const SENT_TYPE: Record<string, string> = {
  AppInstall: "INSTALL",
  AppUninstall: "UNINSTALL",
  PlanChange: "PLAN_CHANGE",
  ConversationUnreadWebhook: "ConversationUnreadUpdate",
};
const docName = (source: string): string => basename(source, ".md");
const names = [
  ...new Set(
    catalog.events.map((event) => {
      const name = docName(event.source);
      return SENT_TYPE[name] ?? name;
    }),
  ),
].sort();
const members = names.map((name) => `  | ${JSON.stringify(name)}`).join("\n");
const source = `/**
 * Every webhook event type in the committed catalog, named from its doc page.
 * Generated by scripts/generate-event-names.ts; regenerate, never edit.
 *
 * @module
 */

/** A webhook event name GoHighLevel documents. */
export type WebhookEventName =
${members};

/** The same names as a runtime list. */
export const WEBHOOK_EVENT_NAMES: readonly WebhookEventName[] = ${JSON.stringify(names)};
`;
await writeFile(target, await format(source, { parser: "typescript", printWidth: 88 }));
say(`Generated ${names.length} webhook event names.`);
